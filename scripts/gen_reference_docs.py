#!/usr/bin/env python3
"""
Regenerate the reference pages under docs/reference/ from the code itself.

    python scripts/gen_reference_docs.py          # rewrite the pages
    python scripts/gen_reference_docs.py --check  # exit 1 if they are stale (used by a test)

    docs/reference/api.md             every HTTP route, from the live FastAPI app's OpenAPI schema
    docs/reference/configuration.md   every API setting (from apps/api/config.py, including its
                                      comments) plus every NEXT_PUBLIC_* variable the web app reads

Why generated: hand-written reference tables go stale silently.  apps/api/test_docs_in_sync.py
fails the suite when these pages differ from what this script produces, so the reference can only
change together with the code.  Defaults are read from SOURCE, never from the environment, so no
value from a developer's .env can leak into the docs.
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference"
NOTICE = ("> Generated by `scripts/gen_reference_docs.py` — do not edit by hand. "
          "Run `python scripts/gen_reference_docs.py` after changing the code.\n")


def _project_files(prefix: str) -> list[Path]:
    """Files under `prefix` that git considers part of the project: tracked, plus untracked-but-
    not-ignored.  NEVER walk the filesystem: a developer's git-ignored files (.env.local, build
    output, scratch) would leak their names into the docs and make the pages differ between a
    working copy and a clean clone.  A page generated here must be reproducible anywhere."""
    import subprocess
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "--cached", "--others",
                          "--exclude-standard", prefix], capture_output=True, text=True, check=True).stdout
    return sorted(ROOT / line for line in out.splitlines() if (ROOT / line).is_file())


def _clean(text: str, limit: int = 170) -> str:
    """First paragraph, RST-ish markup flattened, first sentence, capped, table-safe."""
    if not text:
        return ""
    para: list[str] = []
    for line in text.strip().splitlines():
        if not line.strip():
            if para:
                break
            continue
        para.append(line.strip())
    s = " ".join(para)
    s = s.replace("``", "`")
    s = re.sub(r"\s+", " ", s)
    m = re.search(r"(?<=[a-z0-9\)`])\. (?=[A-Z])", s)        # end of first sentence
    if m and m.start() < limit + 40:
        s = s[: m.start() + 1]
    if len(s) > limit:
        s = s[: limit - 1].rstrip() + "…"
    return s.replace("|", "\\|")


# ── API ────────────────────────────────────────────────────────────────────────────────────

def render_api() -> str:
    warnings.filterwarnings("ignore")
    sys.path.insert(0, str(ROOT))
    from apps.api.main import app

    spec = app.openapi()
    groups: dict[str, list[tuple[str, str, str, str]]] = {}
    n = 0
    for path, ops in spec["paths"].items():
        parts = path.strip("/").split("/")
        group = parts[1] if parts[0] == "api" and len(parts) > 1 else "service"
        for method, op in ops.items():
            if method.upper() not in {"GET", "POST", "PUT", "PATCH", "DELETE"}:
                continue
            body = (op.get("requestBody", {}).get("content", {})
                    .get("application/json", {}).get("schema", {}))
            ref = body.get("$ref", "").rsplit("/", 1)[-1] if body else ""
            desc = _clean(op.get("description") or op.get("summary") or "")
            groups.setdefault(group, []).append((path, method.upper(), desc, ref))
            n += 1

    lines = ["# API reference", "", NOTICE,
             f"{n} endpoints in {len(groups)} groups. With the server running, interactive "
             "documentation (try-it-out, full request/response schemas) is served at `/docs`, "
             "and the machine-readable schema at `/openapi.json`.", "",
             "Cost-bearing endpoints can be gated by authentication and a credit check; see "
             "[Architecture](../architecture.md#request-pipeline) and "
             "[Deployment](../deployment.md#security-checklist). With no auth configured the API "
             "runs open.", ""]
    for group in sorted(groups):
        title = f"/api/{group}" if group != "service" else "service (unprefixed)"
        lines += [f"## {group}", "", f"Routes under `{title}`.", "",
                  "| Method | Path | Description | Request body |", "|---|---|---|---|"]
        for path, method, desc, ref in sorted(groups[group]):
            lines.append(f"| `{method}` | `{path}` | {desc} | {f'`{ref}`' if ref else ''} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# ── configuration ──────────────────────────────────────────────────────────────────────────

def _settings_fields() -> list[tuple[str, str, str, str, str]]:
    """(section, ENV_NAME, type, default, description) parsed from config.py source."""
    src = (ROOT / "apps" / "api" / "config.py").read_text()
    lines = src.splitlines()
    tree = ast.parse(src)
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Settings")
    out, section = [], "General"
    for node in cls.body:
        if not (isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name)):
            continue
        # contiguous comment block immediately above the field
        block: list[str] = []
        i = node.lineno - 2
        while i >= 0 and lines[i].strip().startswith("#"):
            block.insert(0, lines[i].strip().lstrip("#").strip())
            i -= 1
        desc_parts = []
        for b in block:
            if "──" in b:                                  # section banner, e.g. "── Cross-origin access ──"
                title = b.strip("─ ").strip()
                if title:
                    section = title
                continue
            if b:
                desc_parts.append(b)
        tail = lines[node.end_lineno - 1][node.end_col_offset:]
        if "#" in tail:
            desc_parts.append(tail.split("#", 1)[1].strip())
        default = ast.unparse(node.value) if node.value is not None else "(required)"
        out.append((section, node.target.id.upper(), ast.unparse(node.annotation), default,
                    _clean(" ".join(desc_parts), limit=260)))
    return out


def _web_env_vars() -> list[tuple[str, str]]:
    seen: dict[str, str] = {}
    for p in _project_files("apps/web"):
        if p.suffix not in {".ts", ".tsx", ".js", ".mjs", ".cjs", ".json"}:
            continue
        if ".test." in p.name:                           # a test is not where a setting is read
            continue
        try:
            text = p.read_text(errors="ignore")
        except OSError:
            continue
        for name in re.findall(r"NEXT_PUBLIC_[A-Z0-9_]+", text):
            seen.setdefault(name, str(p.relative_to(ROOT)))
    return sorted(seen.items())


_DIRECT_ENV_NOTES = {
    "LEILMAT_PAPERS_DIR": "Directory of PDFs that `rag.pipeline.preload_papers()` ingests into ChromaDB "
                          "(default `./Alloys Design`; nothing ships there).",
}


def _direct_env_vars(settings_names: set[str]) -> list[tuple[str, str, str]]:
    """(NAME, where, note) for variables read via os.environ/os.getenv but NOT declared on Settings."""
    rx = re.compile(r"""os\.(?:environ\.get|getenv|environ)\s*[\(\[]\s*["']([A-Z][A-Z0-9_]+)["']""")
    found: dict[str, str] = {}
    for p in (q for q in _project_files("apps/api") if q.suffix == ".py"):
        rel = str(p.relative_to(ROOT))
        if "test_" in rel or "/eval/" in rel or "conftest" in rel:
            continue
        text = p.read_text(errors="ignore")            # whole file: the name may follow a line break
        for m in rx.finditer(text):
            found.setdefault(m.group(1), rel)   # no line numbers: they would make the page 'stale' on unrelated edits
    return [(n, w, _DIRECT_ENV_NOTES.get(n, "(see source)")) for n, w in sorted(found.items())
            if n not in settings_names]


def render_config() -> str:
    fields = _settings_fields()
    lines = ["# Configuration reference", "", NOTICE,
             "Settings are read from environment variables (or a `.env` file in the working "
             "directory); names are case-insensitive. Copy [`.env.example`](../../.env.example) "
             "to `.env` to start. Everything beyond the database, ChromaDB and (optionally) an "
             "LLM key is an **optional integration that is off unless configured** — see "
             "[Deployment](../deployment.md).", "",
             "Defaults shown are the values in source. Secrets default to empty.", ""]
    sections: dict[str, list] = {}
    for sec, env, typ, default, desc in fields:
        sections.setdefault(sec, []).append((env, typ, default, desc))
    for sec, rows in sections.items():
        lines += [f"## {sec}", "", "| Variable | Type | Default | Description |", "|---|---|---|---|"]
        for env, typ, default, desc in rows:
            lines.append(f"| `{env}` | `{typ}` | `{default}` | {desc} |")
        lines.append("")
    direct = _direct_env_vars({f[1] for f in fields})
    if direct:
        lines += ["## Read directly from the environment", "",
                  "Not part of the settings object, so a value that exists only in `.env` is "
                  "**not** seen unless your runner exports it (Docker Compose's `env_file` does).", "",
                  "| Variable | Read in | Description |", "|---|---|---|"]
        lines += [f"| `{n}` | `{w}` | {note} |" for n, w, note in direct]
        lines.append("")
    web = _web_env_vars()
    lines += ["## Web app (build-time)", "",
              "Next.js inlines `NEXT_PUBLIC_*` variables **at build time**, so they must be present "
              "when the web image or bundle is built, not only when it runs. Detected by scanning "
              "`apps/web`:", "", "| Variable | First referenced in |", "|---|---|"]
    lines += [f"| `{name}` | `{where}` |" for name, where in web]
    return "\n".join(lines).rstrip() + "\n"


PAGES = {"api.md": render_api, "configuration.md": render_config}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, fn in PAGES.items():
        text = fn()
        path = OUT / name
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}  ({len(text.splitlines())} lines)")
    if a.check and stale:
        print("stale:", ", ".join(stale), "— run: python scripts/gen_reference_docs.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
